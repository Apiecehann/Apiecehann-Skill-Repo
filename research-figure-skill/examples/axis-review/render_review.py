def read(name):
    return backend.load_data(HERE / "data" / name)


def mix(color, t):
    h = color.lstrip("#")
    rgb = [int(h[i:i + 2], 16) for i in (0, 2, 4)]
    return "#" + "".join(f"{round(c + (255 - c) * t):02x}" for c in rgb)


def font_roles(path, family, bold_path=None):
    roles = {}
    for role in ("light", "regular", "bold", "mono", "heading", "heading_bold"):
        bold = role in ("bold", "heading_bold")
        roles[role] = {"family": family, "weight": "bold" if bold else "normal",
                       "file": bold_path if bold and bold_path else path}
    return roles


def config(rows, *, style="paper-clean", layout="grouped", size="single",
           font="sans", colors=None, labels=None, grid="none", legend=True,
           fill=None, edge=None, hatch=None, fonts=None, baseline_only=False,
           tick_format=".0%", ylabel="Success rate", panels=None, gains=None,
           capacity=None, reference_lines=None, figure_size=None):
    order = list(dict.fromkeys(row["series"] for row in rows))
    palette = {}
    if colors:
        for series, color in zip(order, colors):
            entry = {"fill": color, "edge": color, "label": "#20252c"}
            if baseline_only and series != "ours":
                entry["fill_alpha"] = fill
                if hatch:
                    entry["hatch"] = hatch
                    entry["edge"] = "#20252c"
            palette[series] = entry
    panel = {
        "limits": "auto", "ticks": "auto", "tick_format": tick_format,
        "ylabel": ylabel, "value_labels": False,
        "bar_edge_alpha": 1,
    }
    if grid is not None:
        panel["grid"] = dict(GRIDS[grid])
    if fill is not None:
        panel["bar_fill_alpha"] = fill
    if edge is not None:
        panel["bar_edge_width"] = edge
    if capacity:
        panel["capacity"] = capacity
    if reference_lines:
        panel["reference_lines"] = reference_lines
    cfg = {
        "data": str(HERE / "data" / "focus.csv"),
        "figure": {"formats": ["png"], "dpi": 180},
        "preset": {"style": style, "layout": layout, "size": size,
                   "palette": "tol-bright", "font": font},
        "series_order": order,
        "panel_defaults": panel,
        "legend_defaults": {
            "show": legend, "columns": "auto", "loc": "lower center",
            "anchor": [.5, 1.06], "frame": False, "size": 6.5,
            "labels": labels or {}, "handlelength": 1.2,
            "columnspacing": 1.2, "handletextpad": .4, "borderaxespad": 0,
        },
        "palette": palette,
    }
    if panels:
        cfg["panels"] = panels
    if figure_size:
        cfg["figure"]["size_pt"] = figure_size
    if gains:
        cfg["gains"] = gains
    if fonts:
        cfg["fonts"] = fonts
    if hatch:
        cfg["rc"] = {"hatch.linewidth": .8}
    return cfg


def render_panel(rows, cfg, name):
    out = HERE / "panels" / name
    backend.render(cfg, rows, out)
    return out.with_suffix(".png")


def make_sheet(title, subtitle, items, columns, out, cell=(430, 350)):
    title_font = ImageFont.truetype(FONT_PATH, 30)
    label_font = ImageFont.truetype(FONT_PATH, 19)
    note_font = ImageFont.truetype(FONT_PATH, 14)
    head = 78
    rows = (len(items) + columns - 1) // columns
    sheet = Image.new("RGB", (24 * 2 + cell[0] * columns, head + cell[1] * rows + 20), "white")
    draw = ImageDraw.Draw(sheet)
    draw.text((24, 18), title, fill="#20252c", font=title_font)
    draw.text((24, 52), subtitle, fill="#57606c", font=note_font)
    for i, item in enumerate(items):
        x = 24 + (i % columns) * cell[0]
        y = head + (i // columns) * cell[1]
        with Image.open(item["image"]) as source:
            preview = source.convert("RGB")
            preview.thumbnail((cell[0] - 28, cell[1] - 82), Image.Resampling.LANCZOS)
            sheet.paste(preview, (x + (cell[0] - preview.width) // 2, y))
        draw.text((x + 12, y + cell[1] - 72), item["label"], fill="#20252c", font=label_font)
        draw.text((x + 12, y + cell[1] - 44), item["note"], fill="#57606c", font=note_font)
    sheet.save(HERE / out)
    print("wrote", out)


